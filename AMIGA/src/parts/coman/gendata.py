#!/usr/bin/env python3
"""3DSINFLD (COMAN): wave height tables, sine table, palette and the
generated ray march steps (from COMAN/DOLOOP.C)."""
import sys, os, math, struct
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../tools'))
import gfxconv

out = sys.argv[1]
SRC = os.path.join(gfxconv.ROOT, 'COMAN')
H = gfxconv.Header('coman_data.h')
for n in ('W1DTA', 'W2DTA'):
    d = open(os.path.join(SRC, n + '.BIN'), 'rb').read()
    H.array(n.lower(), struct.unpack('<%dh' % (len(d) // 2), d), 's16')
v = []
for l in open(os.path.join(SRC, 'SIN1024.INC'), encoding='latin1'):
    l = l.strip()
    if l.lower().startswith('dw'):
        v += [int(x) for x in l[2:].split(',') if x.strip()]
H.array('csin', v, 's16')

# palette (MAIN.C), 6 bit, entries 0..127 are used by the landscape
pal = [0] * 768
for a in range(256):
    uc = (223 - a * 22 // 26) * 3
    b = int((230 - a) / 4)
    b += int(v[a * 4 & 1023] / 32)
    b = max(0, min(63, b))
    pal[uc + 1] = b
    b = (255 - a) // 3
    pal[uc + 2] = min(63, b)
    b = abs(a - 220)
    b = 40 - min(40, b)
    pal[uc] = b // 3
for a in range(768 - 16 * 3):
    pal[a] = min(63, pal[a] * 9 // 6)
H.array('cpal', pal[:128 * 3])
H.write(out)

# ---- ray march steps: 64 per column (DOLOOP.C has 192 with the far
# half stepping twice; here near steps are 2, far steps 4)
bail, half, horizon = 192, 64, 70
zwave = [int(16.0 * math.sin(i * math.pi * 2.0 * 3.0 / bail)) for i in range(bail)]
steps = [(j, False) for j in range(0, half, 2)] + [(j, True) for j in range(half, bail, 4)]
L = []
L.append('| generated by coman/gendata.py: unrolled ray march')
for k, (j, far) in enumerate(steps):
    if far and not steps[k - 1][1]:
        L += ['\tadd.w\td4,d4', '\tadd.w\td5,d5', '\tadd.l\td7,d7']
    L += ['.Ls%d:' % k,
          '\tadd.w\td4,d0', '\tmove.w\t0(a1,d0.w),d2',
          '\tadd.w\td5,d1', '\tadd.w\t0(a2,d1.w),d2',
          '\tadd.w\t#%d,d2' % (zwave[j] - 240),
          '\tmove.l\td6,d3', '\tswap\td3', '\tcmp.w\td3,d2',
          '\tbgt\t.Lh%d' % k,
          '.Lo%d:' % k,
          '\tadd.l\td7,d6']
L.append('\tbra\t.Ldone')
for k, (j, far) in enumerate(steps):
    L += ['.Lh%d:' % k,
          '\tmove.w\td2,d3', '\tadd.w\t#%d,d3' % (120 - j // 8), '\tand.w\t#0xfe,d3',
          '\tmove.w\t0(a6,d3.w),d3',
          '\tswap\td2', '\tclr.w\td2',
          '.Lp%d:' % k,
          '\tmove.w\td3,(a3)', '\tmove.w\td3,LSLOT(a3)',
          '\tlea\t-2*LSLOT(a3),a3',
          '\tcmp.l\ta5,a3', '\tbcs\t.Lfull',
          '\tadd.l\t#%d,d6' % (2 * j * 2560),
          '\tadd.l\t#%d,d7' % ((4 if far else 2) * 2 * 2560),
          '\tcmp.l\td6,d2', '\tbgt\t.Lp%d' % k,
          '\tbra\t.Lo%d' % k]
open(os.path.join(out, 'coman_steps.i'), 'w').write('\n'.join(L) + '\n')
