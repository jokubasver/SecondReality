#!/usr/bin/env python3
"""
Build script for the Second Reality Amiga port.

  python3 build.py            build everything -> build/SecondReality1.adf, ...2.adf
  python3 build.py --test X   boot straight into part X (for quick testing)
"""
import os
import shutil, sys, subprocess, struct, glob, argparse

ROOT = os.path.dirname(os.path.abspath(__file__))
B = os.path.join(ROOT, 'build')
CC = 'm68k-linux-gnu-gcc'
AS = 'm68k-linux-gnu-as'
LD = 'm68k-linux-gnu-ld'
OBJCOPY = 'm68k-linux-gnu-objcopy'
NM = 'm68k-linux-gnu-nm'
LIBGCC = subprocess.check_output([CC, '-m68000', '-print-libgcc-file-name']).decode().strip()
CFLAGS = ['-m68000', '-mstrict-align', '-O2', '-fno-store-merging', '-fno-expensive-optimizations', '-fomit-frame-pointer', '-ffreestanding', '-nostdlib', '-fno-pic',
          '-fno-common', '-fno-tree-loop-distribute-patterns', '-fno-strict-aliasing',
          '-Wall', '-Wno-unused-function',
          '-I' + os.path.join(ROOT, 'src/kernel'), '-I' + os.path.join(B, 'gen')]
ADF_SIZE = 901120

sys.path.insert(0, os.path.join(ROOT, 'tools'))
from manifest import FILES, MUSIC, PARTS


def run(cmd, **kw):
    r = subprocess.run(cmd, **kw)
    if r.returncode:
        print('FAILED:', ' '.join(cmd))
        sys.exit(1)


def newer(target, deps):
    if not os.path.exists(target):
        return True
    t = os.path.getmtime(target)
    return any(os.path.getmtime(d) > t for d in deps if os.path.exists(d))


def compile_dir(srcs, objdir, extra=()):
    os.makedirs(objdir, exist_ok=True)
    hdrs = (glob.glob(os.path.join(ROOT, 'src/kernel/*.h')) + glob.glob(os.path.join(B, 'gen/*.h')) +
            glob.glob(os.path.join(B, 'gen/*.i')))
    objs = []
    for s in srcs:
        o = os.path.join(objdir, os.path.basename(s).rsplit('.', 1)[0] + '.o')
        deps = [s] + hdrs + glob.glob(os.path.join(os.path.dirname(s), '*.h')) + glob.glob(os.path.join(ROOT, 'src/common/*'))
        if newer(o, deps):
            if s.endswith('.S'):
                run([AS, '-m68000', '--register-prefix-optional', '-I', os.path.join(B, 'gen'), '-o', o, s])
            else:
                run([CC] + CFLAGS + list(extra) + ['-I' + os.path.dirname(s), '-c', '-o', o, s])
        objs.append(o)
    return objs


def gen_files_h():
    os.makedirs(os.path.join(B, 'gen'), exist_ok=True)
    s = '/* generated by build.py */\n#ifndef FILES_H\n#define FILES_H\n'
    for i, f in enumerate(FILES):
        s += '#define F_%s %d\n' % (f[0], i)
    s += '#define F_COUNT %d\n#endif\n' % len(FILES)
    p = os.path.join(B, 'gen/files.h')
    if not os.path.exists(p) or open(p).read() != s:
        open(p, 'w').write(s)


def build_music():
    trim = '/* generated by build.py: music bank sizes after a song position */\n'
    for name, s3m, orders, budget, opts in MUSIC:
        out = os.path.join(B, 'music', name)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        deps = [os.path.join(ROOT, s3m), os.path.join(ROOT, 'tools/s3m2paula.py'),
                os.path.join(ROOT, 'tools/paula_alloc.py'), os.path.join(ROOT, 'tools/manifest.py')]
        deps += [os.path.join(ROOT, o) for o in opts if o.endswith('.json')]
        if newer(out + '.smp', deps):
            for f in glob.glob(out + '*'):
                os.remove(f)
            run([sys.executable, os.path.join(ROOT, 'tools/s3m2paula.py'), os.path.join(ROOT, s3m),
                 out, '--orders', orders, '--budget', str(budget)] +
                [os.path.join(ROOT, o) if o.endswith('.json') else o for o in opts])
        if os.path.exists(out + '.trim'):
            o, n = open(out + '.trim').read().split()
            trim += '#define %s_TRIM_ORDER %s\n#define %s_TRIM_BYTES %s\n' % (name.upper(), o, name.upper(), n)
    p = os.path.join(B, 'gen/music_trim.h')
    os.makedirs(os.path.dirname(p), exist_ok=True)
    if not os.path.exists(p) or open(p).read() != trim:
        open(p, 'w').write(trim)


def build_kernel(defs):
    srcs = [os.path.join(ROOT, 'src/kernel', x) for x in
            ('start.S', 'kernel.c', 'loader.c', 'music.c', 'lib.c', 'sintab.c', 'demo.c', 'panic.c', 'gfx.c', 'math.S', 'unlz.S', 'mixer.c', 'mixasm.S')]
    objs = compile_dir(srcs, os.path.join(B, 'obj/kernel'), defs)
    elf = os.path.join(B, 'kernel.elf')
    run([LD, '--no-warn-rwx-segments', '-z', 'noexecstack', '-T', os.path.join(ROOT, 'tools/kernel.ld'), '-o', elf] + objs)
    run([OBJCOPY, '-O', 'binary', elf, os.path.join(B, 'kernel.bin')])
    return elf


def build_part(name, defs):
    d = os.path.join(ROOT, 'src/parts', name)
    gen = os.path.join(d, 'gendata.py')
    if os.path.exists(gen):
        stamp = os.path.join(B, 'gen', name + '.stamp')
        deps = [gen] + glob.glob(os.path.join(ROOT, 'tools/*.py')) + glob.glob(os.path.join(d, '*.png'))
        if newer(stamp, deps):
            run([sys.executable, gen, os.path.join(B, 'gen')], cwd=d)
            open(stamp, 'w').write('ok')
    srcs = sorted(glob.glob(os.path.join(d, '*.c')) + glob.glob(os.path.join(d, '*.S')))
    if os.path.exists(os.path.join(d, 'common.txt')):
        srcs += [os.path.join(ROOT, 'src/common', x.strip()) for x in open(os.path.join(d, 'common.txt')) if x.strip()]
    objs = compile_dir(srcs, os.path.join(B, 'obj', name), defs)
    elf = os.path.join(B, 'parts', name + '.elf')
    os.makedirs(os.path.dirname(elf), exist_ok=True)
    run([LD, '--no-warn-rwx-segments', '-z', 'noexecstack', '-q', '-T', os.path.join(ROOT, 'tools/part.ld'), '-R', os.path.join(B, 'kernel.elf'),
         '-o', elf] + objs)
    run([sys.executable, os.path.join(ROOT, 'tools/mkpart.py'), elf,
         os.path.join(B, 'parts', name + '.prt')], stdout=subprocess.DEVNULL)


def pack(name, path, mode):
    """Returns (data, flags, margin, unpacked size)."""
    src = os.path.join(ROOT, path) if not os.path.isabs(path) else path
    size = os.path.getsize(src)
    if mode == 'store':
        d = open(src, 'rb').read()
        if len(d) & 1: d += b'\0'
        return d, 1, 0, size
    out = os.path.join(B, 'packed', name + '.lz')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    mfile = out + '.margin'
    if newer(out, [src]) or not os.path.exists(mfile):
        args = [os.path.join(ROOT, 'tools/lzpack')] + (['-d'] if mode == 'delta' else []) + [src, out]
        r = subprocess.run(args, capture_output=True, check=True)
        open(mfile, 'w').write(r.stdout.decode().strip())
    d = open(out, 'rb').read()
    if len(d) & 1: d += b'\0'
    return d, 0, int(open(mfile).read()), size


def symbol(elf, name):
    for line in subprocess.check_output([NM, elf]).decode().splitlines():
        p = line.split()
        if p[-1] == name:
            return int(p[0], 16)
    raise KeyError(name)


def make_disks():
    import mkadf
    kernel = bytearray(open(os.path.join(B, 'kernel.bin'), 'rb').read())
    ksize = (len(kernel) + 511) & ~511
    kernel += bytes(ksize - len(kernel))
    diroff = symbol(os.path.join(B, 'kernel.elf'), 'k_dir') - 0x400
    disks = {1: bytearray(ADF_SIZE), 2: bytearray(ADF_SIZE)}
    pos = {1: 1024 + ksize, 2: 1024}
    used = {1: False, 2: False}
    for i, (name, path, mode, disk) in enumerate(FILES):
        data, flags, margin, size = pack(name, path, mode)
        off = pos[disk]
        if off + len(data) > ADF_SIZE:
            sys.exit('disk %d full while adding %s (%d bytes)' % (disk, name, len(data)))
        disks[disk][off:off + len(data)] = data
        pos[disk] = off + len(data)
        used[disk] = True
        struct.pack_into('>BBHIII', kernel, diroff + i * 16, disk, flags, margin, off, len(data), size)
        print('  %-14s disk %d  %7d -> %7d' % (name, disk, size, len(data)))
    # bootblock
    bb = os.path.join(B, 'boot.o')
    run([AS, '-m68000', '--register-prefix-optional', '--defsym', 'KSIZE=%d' % ksize, '-o', bb,
         os.path.join(ROOT, 'src/kernel/boot.S')])
    run([OBJCOPY, '-O', 'binary', bb, bb + '.bin'])
    code = bytearray(open(bb + '.bin', 'rb').read())
    code += bytes(1008 - len(code)) + struct.pack('>I', 0x53524401)  # id at 1020
    disks[1][0:1024] = mkadf.make_bootblock(bytes(code))
    disks[1][1024:1024 + ksize] = kernel
    struct.pack_into('>I', disks[2], 1020, 0x53524402)
    for n in (1, 2):
        if used[n] or n == 1:
            p = os.path.join(B, 'SecondReality%d.adf' % n)
            open(p, 'wb').write(disks[n])
            print('%s: %d of %d bytes used (%.0f%%)' % (p, pos[n], ADF_SIZE, 100.0 * pos[n] / ADF_SIZE))


def asm_bin(src, out, syms=()):
    o = out + '.o'
    args = [AS, '-m68000', '--register-prefix-optional']
    for k, v in syms:
        args += ['--defsym', '%s=%d' % (k, v)]
    run(args + ['-o', o, src])
    run([OBJCOPY, '-O', 'binary', o, out])
    return open(out, 'rb').read()


def build_whdload():
    """WHDLoad slave (hunk executable) and the install directory."""
    code = asm_bin(os.path.join(ROOT, 'src/whdload/slave.S'), os.path.join(B, 'slave.bin'))
    code += bytes(-len(code) % 4)
    n = len(code) // 4
    hunk = struct.pack('>IIIIII', 0x3f3, 0, 1, 0, 0, n) + struct.pack('>II', 0x3e9, n) + code + \
        struct.pack('>I', 0x3f2)
    d = os.path.join(B, 'whdload', 'SecondReality')
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'SecondReality.slave'), 'wb').write(hunk)
    for i in (1, 2):
        shutil.copyfile(os.path.join(B, 'SecondReality%d.adf' % i), os.path.join(d, 'disk.%d' % i))
    shutil.copyfile(os.path.join(ROOT, 'src/whdload/ReadMe'), os.path.join(d, 'ReadMe'))
    print('%s: WHDLoad install (slave %d bytes)' % (d, len(hunk)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--test', help='start directly with this part')
    ap.add_argument('--release', action='store_true')
    ap.add_argument('--skip-intro', action='store_true')
    ap.add_argument('--music', type=int, default=0, help='test mode: music 0 or 1')
    ap.add_argument('--order', type=int, default=0, help='test mode: start music at this order')
    a = ap.parse_args()
    defs = [] if a.release else ['-DDEBUG']
    if a.skip_intro:
        defs.append('-DSKIP_INTRO')
    if os.environ.get('MIXBENCH'):
        defs.append('-DMIXBENCH')
    if os.environ.get('V3PROF'):
        defs.append('-DV3PROF')
    if os.environ.get('FPSSTAT'):
        defs.append('-DFPSSTAT')
    if os.environ.get('MEMSTAT'):
        defs.append('-DMEMSTAT')
    if os.environ.get('OVERLAY'):
        defs.append('-DDEBUG_OVERLAY')
    if a.test:
        defs.append('-DTEST_PART=F_PART_%s' % a.test.upper())
        defs.append('-DTEST_MUSIC=%d' % a.music)
        defs.append('-DTEST_ORDER=%d' % a.order)
    if newer(os.path.join(ROOT, 'tools/lzpack'), [os.path.join(ROOT, 'tools/lzpack.c'),
                                                   os.path.join(ROOT, 'src/common/unlz.h')]):
        run(['gcc', '-O2', '-o', os.path.join(ROOT, 'tools/lzpack'), os.path.join(ROOT, 'tools/lzpack.c')])
    build_music()
    gen_files_h()
    run([sys.executable, os.path.join(ROOT, 'tools/kmsg.py'), os.path.join(B, 'gen')])
    # kernel objects depend on defines: force rebuild of demo.o/kernel.o when they change
    stamp = os.path.join(B, 'obj/defs')
    os.makedirs(os.path.dirname(stamp), exist_ok=True)
    if not os.path.exists(stamp) or open(stamp).read() != ' '.join(defs):
        for o in glob.glob(os.path.join(B, 'obj/*/*.o')):
            os.remove(o)
        open(stamp, 'w').write(' '.join(defs))
    build_kernel(defs)
    for p in PARTS:
        build_part(p, defs)
    make_disks()
    build_whdload()


if __name__ == '__main__':
    main()
